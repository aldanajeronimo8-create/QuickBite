CREATE OR REPLACE FUNCTION public.record_system_health_check(
  p_service TEXT,
  p_status TEXT,
  p_latency_ms INTEGER DEFAULT NULL,
  p_details JSONB DEFAULT '{}'::jsonb
)
RETURNS BIGINT
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_id BIGINT;
  v_service TEXT := lower(trim(COALESCE(p_service, '')));
BEGIN
  IF v_service = '' OR p_status NOT IN ('healthy', 'degraded', 'unhealthy') THEN
    RAISE EXCEPTION 'invalid_health_check';
  END IF;
  IF p_latency_ms IS NOT NULL AND p_latency_ms < 0 THEN
    RAISE EXCEPTION 'invalid_health_latency';
  END IF;
  IF jsonb_typeof(COALESCE(p_details, '{}'::jsonb)) <> 'object'
    OR public.audit_payload_has_sensitive_key(COALESCE(p_details, '{}'::jsonb)) THEN
    RAISE EXCEPTION 'sensitive_health_metadata';
  END IF;

  -- A public health endpoint can be probed frequently. Store at most one
  -- identical result per service/status per minute, while still recording
  -- transitions immediately.
  SELECT id INTO v_id
  FROM public.system_health_checks
  WHERE service = v_service
    AND status = p_status
    AND checked_at >= NOW() - INTERVAL '1 minute'
  ORDER BY checked_at DESC
  LIMIT 1;

  IF v_id IS NOT NULL THEN
    RETURN v_id;
  END IF;

  INSERT INTO public.system_health_checks (service, status, latency_ms, details)
  VALUES (v_service, p_status, p_latency_ms, COALESCE(p_details, '{}'::jsonb))
  RETURNING id INTO v_id;
  RETURN v_id;
END;
$$;

REVOKE ALL ON FUNCTION public.record_system_health_check(TEXT, TEXT, INTEGER, JSONB) FROM PUBLIC, anon, authenticated;
GRANT EXECUTE ON FUNCTION public.record_system_health_check(TEXT, TEXT, INTEGER, JSONB) TO service_role;

CREATE OR REPLACE FUNCTION public.get_system_health_summary()
RETURNS TABLE(
  service TEXT,
  status TEXT,
  latency_ms INTEGER,
  checked_at TIMESTAMPTZ,
  details JSONB
)
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
BEGIN
  IF NOT public.is_admin() THEN
    RAISE EXCEPTION 'not_authorized';
  END IF;

  RETURN QUERY
  SELECT DISTINCT ON (health.service)
    health.service,
    health.status,
    health.latency_ms,
    health.checked_at,
    health.details
  FROM public.system_health_checks AS health
  ORDER BY health.service, health.checked_at DESC;
END;
$$;

