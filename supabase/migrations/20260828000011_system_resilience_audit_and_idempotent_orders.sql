-- Never allow an audit payload to become a secondary place for credentials.
-- The check is recursive so nested objects and arrays are covered too.
CREATE OR REPLACE FUNCTION public.audit_payload_has_sensitive_key(p_payload JSONB)
RETURNS BOOLEAN
LANGUAGE plpgsql
IMMUTABLE
SET search_path = pg_catalog
AS $$
DECLARE
  v_key TEXT;
  v_value JSONB;
BEGIN
  IF p_payload IS NULL OR p_payload IN ('null'::jsonb, '{}'::jsonb, '[]'::jsonb) THEN
    RETURN false;
  END IF;

  CASE jsonb_typeof(p_payload)
    WHEN 'object' THEN
      FOR v_key, v_value IN SELECT key, value FROM jsonb_each(p_payload)
      LOOP
        IF lower(v_key) ~ '(password|passphrase|secret|token|authorization|cookie|api[_-]?key|private[_-]?key|jwt|credential)' THEN
          RETURN true;
        END IF;
        IF public.audit_payload_has_sensitive_key(v_value) THEN
          RETURN true;
        END IF;
      END LOOP;
    WHEN 'array' THEN
      FOR v_value IN SELECT value FROM jsonb_array_elements(p_payload) AS values_table(value)
      LOOP
        IF public.audit_payload_has_sensitive_key(v_value) THEN
          RETURN true;
        END IF;
      END LOOP;
  END CASE;

  RETURN false;
END;
$$;

REVOKE ALL ON FUNCTION public.audit_payload_has_sensitive_key(JSONB) FROM PUBLIC;

-- Internal writer used by database triggers and the authenticated RPC below.
CREATE OR REPLACE FUNCTION public.record_system_audit(
  p_actor_id UUID,
  p_action TEXT,
  p_module TEXT,
  p_operation TEXT,
  p_entity_type TEXT DEFAULT NULL,
  p_entity_id TEXT DEFAULT NULL,
  p_status TEXT DEFAULT 'success',
  p_details JSONB DEFAULT '{}'::jsonb
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public
AS $$
DECLARE
  v_id UUID;
BEGIN
  IF trim(COALESCE(p_action, '')) = ''
    OR trim(COALESCE(p_module, '')) = ''
    OR trim(COALESCE(p_operation, '')) = '' THEN
    RAISE EXCEPTION 'invalid_audit_event';
  END IF;

  IF p_status NOT IN ('success', 'failure') THEN
    RAISE EXCEPTION 'invalid_audit_status';
  END IF;

  IF jsonb_typeof(COALESCE(p_details, '{}'::jsonb)) <> 'object'
    OR public.audit_payload_has_sensitive_key(COALESCE(p_details, '{}'::jsonb)) THEN
    RAISE EXCEPTION 'sensitive_audit_metadata';
  END IF;

  INSERT INTO public.system_audit_logs (
    actor_user_id, action, module, operation, entity_type, entity_id, status, metadata
  ) VALUES (
    p_actor_id,
    left(trim(p_action), 120),
    left(trim(p_module), 80),
    left(trim(p_operation), 80),
    NULLIF(left(trim(COALESCE(p_entity_type, '')), 80), ''),
    NULLIF(left(trim(COALESCE(p_entity_id, '')), 160), ''),
    p_status,
    COALESCE(p_details, '{}'::jsonb)
  )
  RETURNING id INTO v_id;

  RETURN v_id;
END;
$$;

REVOKE ALL ON FUNCTION public.record_system_audit(UUID, TEXT, TEXT, TEXT, TEXT, TEXT, TEXT, JSONB) FROM PUBLIC, anon, authenticated;

-- Browser code may record only its own successful/failed actions. The actor
-- is always derived from the JWT, never trusted from a submitted payload.
CREATE OR REPLACE FUNCTION public.write_system_audit_event(
  p_action TEXT,
  p_entity_type TEXT DEFAULT NULL,
  p_entity_id TEXT DEFAULT NULL,
  p_details JSONB DEFAULT '{}'::jsonb,
  p_status TEXT DEFAULT 'success'
)
RETURNS UUID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
DECLARE
  v_action TEXT := lower(trim(COALESCE(p_action, '')));
  v_module TEXT;
  v_operation TEXT;
BEGIN
  IF auth.uid() IS NULL THEN
    RAISE EXCEPTION 'not_authorized';
  END IF;

  IF v_action !~ '^[a-z][a-z0-9_]{1,79}\.[a-z][a-z0-9_]{1,79}$' THEN
    RAISE EXCEPTION 'invalid_audit_action';
  END IF;

  v_module := split_part(v_action, '.', 1);
  v_operation := split_part(v_action, '.', 2);
  RETURN public.record_system_audit(
    auth.uid(), v_action, v_module, v_operation,
    p_entity_type, p_entity_id, p_status, COALESCE(p_details, '{}'::jsonb)
  );
END;
$$;

REVOKE ALL ON FUNCTION public.write_system_audit_event(TEXT, TEXT, TEXT, JSONB, TEXT) FROM PUBLIC, anon;
GRANT EXECUTE ON FUNCTION public.write_system_audit_event(TEXT, TEXT, TEXT, JSONB, TEXT) TO authenticated;

CREATE OR REPLACE FUNCTION public.audit_business_change()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = pg_catalog, public, auth
AS $$
DECLARE
  v_actor_id UUID := auth.uid();
  v_action TEXT;
  v_module TEXT;
  v_operation TEXT;
  v_entity_type TEXT := TG_TABLE_NAME;
  v_entity_id TEXT;
  v_details JSONB;
BEGIN
  IF TG_OP = 'DELETE' THEN
    v_entity_id := OLD.id::text;
  ELSE
    v_entity_id := NEW.id::text;
  END IF;

  IF TG_TABLE_NAME = 'products' THEN
    IF TG_OP = 'INSERT' THEN
      v_action := 'product.create';
      v_module := 'catalog';
      v_operation := 'create';
      v_details := jsonb_build_object('name', NEW.name, 'stock', NEW.stock, 'available', NEW.available);
    ELSIF TG_OP = 'DELETE' THEN
      v_action := 'product.delete';
      v_module := 'catalog';
      v_operation := 'delete';
      v_details := jsonb_build_object('name', OLD.name, 'stock', OLD.stock);
    ELSIF OLD.stock IS DISTINCT FROM NEW.stock THEN
      v_action := 'inventory.update';
      v_module := 'inventory';
      v_operation := 'adjust';
      v_details := jsonb_build_object(
        'product_name', NEW.name,
        'previous_stock', OLD.stock,
        'stock', NEW.stock,
        'delta', NEW.stock - OLD.stock
      );
    ELSE
      v_action := 'product.update';
      v_module := 'catalog';
      v_operation := 'update';
      v_details := jsonb_build_object('name', NEW.name, 'price', NEW.price, 'available', NEW.available);
    END IF;
  ELSIF TG_TABLE_NAME = 'categories' THEN
    v_action := 'category.' || lower(TG_OP);
    v_module := 'catalog';
    v_operation := lower(TG_OP);
    IF TG_OP = 'DELETE' THEN
      v_details := jsonb_build_object('name', OLD.name);
    ELSE
      v_details := jsonb_build_object('name', NEW.name);
    END IF;
  ELSIF TG_TABLE_NAME = 'orders' THEN
    IF TG_OP = 'INSERT' THEN
      v_action := 'order.create';
      v_module := 'orders';
      v_operation := 'create';
      v_details := jsonb_build_object(
        'order_number', NEW.order_number,
        'total', NEW.total,
        'status', NEW.status,
        'payment_status', NEW.payment_status,
        'payment_method', NEW.payment_method
      );
    ELSIF TG_OP = 'DELETE' THEN
      v_action := 'order.delete';
      v_module := 'orders';
      v_operation := 'delete';
      v_details := jsonb_build_object('order_number', OLD.order_number, 'total', OLD.total);
    ELSIF OLD.status IS DISTINCT FROM NEW.status THEN
      v_action := 'order.status_change';
      v_module := 'orders';
      v_operation := 'status_change';
      v_details := jsonb_build_object('order_number', NEW.order_number, 'from', OLD.status, 'to', NEW.status);
    ELSIF OLD.payment_status IS DISTINCT FROM NEW.payment_status THEN
      v_action := 'payment.update';
      v_module := 'payments';
      v_operation := 'status_change';
      v_details := jsonb_build_object('order_number', NEW.order_number, 'from', OLD.payment_status, 'to', NEW.payment_status);
    ELSIF OLD.admin_hidden IS DISTINCT FROM NEW.admin_hidden THEN
      v_action := 'order.archive';
      v_module := 'sales';
      v_operation := CASE WHEN NEW.admin_hidden THEN 'close_period' ELSE 'restore_period' END;
      v_details := jsonb_build_object('order_number', NEW.order_number, 'hidden', NEW.admin_hidden);
    ELSE
      v_action := 'order.update';
      v_module := 'orders';
      v_operation := 'update';
      v_details := jsonb_build_object('order_number', NEW.order_number);
    END IF;
  ELSIF TG_TABLE_NAME = 'profiles' THEN
    v_action := 'user.' || lower(TG_OP);
    v_module := 'users';
    v_operation := lower(TG_OP);
    IF TG_OP = 'DELETE' THEN
      v_details := jsonb_build_object('role', OLD.role);
    ELSE
      v_details := jsonb_build_object('role', NEW.role);
    END IF;
  ELSE
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
  END IF;

  PERFORM public.record_system_audit(
    v_actor_id, v_action, v_module, v_operation, v_entity_type, v_entity_id, 'success', v_details
  );
  IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
  RETURN NEW;
END;
$$;

